#!/usr/bin/env python3
"""Regenerate RESULTS.md from tracked shapes and cache geometry (stdlib only)."""

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
BENCHMARKS = ("vgg16_T4_n5", "resnet19_T4_n5")
CORPUS = ROOT.parent / "neuro_cache_bench_trace/out_real"
LAYOUTS = ("khkw_split", "cin_khkw_concat")
CORES = 16


def ceil_div(n, d):
    return (n + d - 1) // d


def line_of(layout, cout_blk, cin_blk, pos, n_cin, n_cout, n_pos):
    if layout == "khkw_split":
        # Mirror constructor strides and line_of in
        # src/lays/cachesim/native/src/layout/khkw_split.cpp.
        n_pos_lo = min(8, n_pos)
        stride_cin = n_pos_lo
        stride_cout = n_cin * n_pos_lo
        stride_pos_hi = n_cout * stride_cout
        return (pos // n_pos_lo * stride_pos_hi
                + cout_blk * stride_cout + cin_blk * stride_cin
                + pos % n_pos_lo)
    if layout == "cin_khkw_concat":
        # Proposed flatten in docs/plans/2026-11-04-cin-khkw-concat-layout-plan.md,
        # section 2: d = cin_blk * (KH*KW) + pos; line = cout_blk * D + d.
        return cout_blk * (n_cin * n_pos) + cin_blk * n_pos + pos
    raise ValueError("Unknown layout: " + layout)


def analyze(layer, layout, num_sets):
    counts = [0] * num_sets
    core_sets = [set() for _ in range(CORES)]
    for cout_blk in range(layer["n_cout"]):
        core = cout_blk // layer["slice"]
        for cin_blk in range(layer["n_cin"]):
            for pos in range(layer["n_pos"]):
                line = line_of(layout, cout_blk, cin_blk, pos,
                               layer["n_cin"], layer["n_cout"], layer["n_pos"])
                set_id = line % num_sets
                counts[set_id] += 1
                core_sets[core].add(set_id)
    reached = [len(sets) for sets in core_sets]
    return {
        "global": sum(count > 0 for count in counts),
        "core_min": min(reached),
        "core_mean": sum(reached) / CORES,
        "imbalance": max(counts) / (layer["lines"] / num_sets),
    }


def read_inputs():
    config = json.loads((ROOT / "examples/cache/base.json").read_text())
    line_bytes = config["cin_block"] * config["cout_block"] * config["weight_bytes"]
    levels = {}
    for name in ("l1", "l2"):
        size, assoc = config[name + "_size_bytes"], config[name + "_assoc"]
        if size % (assoc * line_bytes):
            raise ValueError(name + " capacity is not an integral number of sets")
        levels[name.upper()] = {"size": size, "assoc": assoc,
                                "lines": size // line_bytes,
                                "sets": size // (assoc * line_bytes)}
    layers = []
    captures = sorted(CORPUS.glob("*/*/meta.json"))
    if not captures:
        raise FileNotFoundError("No real capture metadata found under " + str(CORPUS))
    sources = [("B09/examples/loas/" + benchmark, "examples",
                ROOT / "examples/input_trace/loas" / benchmark / "meta.json")
               for benchmark in BENCHMARKS]
    sources.extend((path.parent.relative_to(CORPUS).as_posix(), "out_real", path)
                   for path in captures)
    for benchmark, population, path in sources:
        meta = json.loads(path.read_text())
        for name, shape in sorted(meta["layers"].items()):
            params = meta["layer_params"][name]
            cin, cout, kernel = shape[2], params["cout"], params["kernel"]
            is_gemm = name in meta.get("gemm", {})
            if is_gemm:
                gemm = meta["gemm"][name]
                if (cin, cout) != (gemm["K"], gemm["N"]):
                    raise ValueError(f"Inconsistent GEMM dimensions: {path}: {name}")
                kernel = 1
            n_cin = ceil_div(cin, config["cin_block"])
            n_cout = ceil_div(cout, config["cout_block"])
            n_pos = kernel * kernel
            layers.append({"benchmark": benchmark, "name": name,
                           "population": population, "type": "GEMM" if is_gemm else "Conv",
                           "cin": cin, "cout": cout, "kernel": kernel,
                           "stride": params["stride"], "n_cin": n_cin,
                           "n_cout": n_cout, "n_pos": n_pos,
                           "D": n_cin * n_pos, "slice": ceil_div(n_cout, CORES),
                           "lines": n_cout * n_cin * n_pos})
    return config, line_bytes, levels, layers


def label(layer):
    return layer["benchmark"] + "/" + layer["name"]


def pct(n, d):
    return f"{100 * n / d:.2f}%"


def render():
    config, line_bytes, levels, layers = read_inputs()
    results = {(label(layer), layout, level): analyze(layer, layout, geometry["sets"])
               for layer in layers for layout in LAYOUTS
               for level, geometry in levels.items()}
    out = [
        "# Static cache set utilization", "",
        "Generated by `python3 zoo/set_utilization/compute.py` from the repository root, "
        "or `python3 compute.py` from this directory. No third-party packages are required.", "",
        "## Inputs and interpretation", "",
        "Inputs retain the B09 example [VGG16 meta.json]"
        "(../../examples/input_trace/loas/vgg16_T4_n5/meta.json) and [ResNet19 meta.json]"
        "(../../examples/input_trace/loas/resnet19_T4_n5/meta.json), and include every "
        "`*/*/meta.json` under the sibling `neuro_cache_bench_trace/out_real/` directory. "
        "Synthetic `out/` and `out_second/` captures are excluded. "
        f"There are {len(layers)} rows: "
        f"{sum(layer['population'] == 'out_real' for layer in layers)} real-corpus layers "
        f"and {sum(layer['population'] == 'examples' for layer in layers)} retained example layers. "
        "The examples are labeled `B09/examples/loas/...` and counted separately from "
        "the real corpus to avoid treating duplicate shape populations as new captures.", "",
        "Shape conventions follow [LAYER_SHAPES.md]"
        "(../../../neuro_cache_bench_trace/LAYER_SHAPES.md). CIN is `layers[name][2]`; "
        "COUT, kernel and stride come from `layer_params[name]`. A layer is GEMM exactly "
        "when listed in `meta.gemm`: KH = KW = 1, CIN = K, COUT = N (checked against "
        "the stored shape and parameters). Other layers are Conv, including 1×1 convs. "
        "All captured layers are included; stride and token count do not change "
        "weight-line placement. The corpus path is required at regeneration time.", "",
        f"[Geometry](../../examples/cache/base.json): CIN block {config['cin_block']}, "
        f"COUT block {config['cout_block']}, {config['weight_bytes']} byte(s) per weight, "
        f"{line_bytes}-byte lines. Channel blocks round up, including partial blocks.", "",
        "**Core assignment assumption:** 16 cores; core c owns COUT blocks "
        "`[c*b, min((c+1)*b, n_cout_blocks))`, where "
        "`b = ceil(n_cout_blocks/16)`. Each core accesses every CIN block and kernel "
        "position for its own COUT slice. Min/mean include all 16 cores (an empty core "
        "contributes zero). Global reach is the union across all layer lines. "
        "For L2, per-core reach is each core's contribution to the shared cache.", "",
        "`split` means the current [khkw_split.cpp]"
        "(../../src/lays/cachesim/native/src/layout/khkw_split.cpp): "
        "`line = (pos//q)*(n_cout_blocks*n_cin_blocks*q) + cout_blk*(n_cin_blocks*q) "
        "+ cin_blk*q + pos%q`, with `q = min(8, KH*KW)`. "
        "`concat` means the [proposed cin_khkw_concat]"
        "(../../docs/plans/2026-11-04-cin-khkw-concat-layout-plan.md): "
        "`D = n_cin_blocks*KH*KW`, `line = cout_blk*D + cin_blk*KH*KW + pos`. "
        "Both use `pos = kh*KW + kw` and `set = line % num_sets`.", "",
        "Reach columns report the percentage of all sets reached. Imbalance is "
        "`max(lines in a set) / (total valid lines / num_sets)` globally, including "
        "unreached sets in the denominator; 1.000 is perfectly balanced. "
        "Lines counts distinct valid weight blocks, not the split layout's address "
        "span or unused ragged-position slots. `bound` flags a layer with fewer "
        "lines than the level's line capacity, so that layer cannot fill the level "
        "under either policy. The ratio is identical for both layouts.", "",
        "These are static reachability and distribution measurements, not measured "
        "occupancy or hit rates. Reaching every set does not imply filling every way. "
        "Per-core L1 residency is further limited by the size of that core's own slice; "
        "the global capacity comparison is only a necessary bound.", "",
    ]
    out.extend(["### Included captures", "",
                "| Population | Benchmark / capture | Layers | GEMM | Conv |",
                "|---|---|---|---|---|"])
    for benchmark in dict.fromkeys(layer["benchmark"] for layer in layers):
        group = [layer for layer in layers if layer["benchmark"] == benchmark]
        gemms = sum(layer["type"] == "GEMM" for layer in group)
        out.append(f"| {group[0]['population']} | {benchmark} | {len(group)} | "
                   f"{gemms} | {len(group) - gemms} |")
    out.append("")
    for level, geometry in levels.items():
        sets, capacity = geometry["sets"], geometry["lines"]
        out.extend([
            f"## {level}: {sets} sets, {geometry['assoc']}-way, {capacity} lines "
            f"({geometry['size']} bytes)", "",
            "Shape is CIN→COUT / kernel / stride; b is the COUT-block slice width per core.", "",
            "| Layer | Type; shape | D; b | Lines / capacity (bound) | split global | "
            "split core min | split core mean | split imbalance | concat global | "
            "concat core min | concat core mean | concat imbalance |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|",
        ])
        for layer in layers:
            cells = [label(layer),
                     f"{layer['type']}; {layer['cin']}→{layer['cout']} / {layer['kernel']}×{layer['kernel']} / {layer['stride']}",
                     f"{layer['D']}; {layer['slice']}",
                     f"{layer['lines']}/{capacity} ({'bound' if layer['lines'] < capacity else 'not bound'})"]
            for layout in LAYOUTS:
                metric = results[label(layer), layout, level]
                cells.extend([pct(metric["global"], sets), pct(metric["core_min"], sets),
                              pct(metric["core_mean"], sets), f"{metric['imbalance']:.3f}"])
            out.append("| " + " | ".join(cells) + " |")
        out.append("")
    out.extend(["## Conclusions", "",
                "### GEMM versus convolution", "",
                "Counts below are layers reaching every set on every one of the 16 cores, "
                "including empty cores in the minimum. Examples are a separate population.", "",
                "| Population | Type | Layers | split L1 full | concat L1 full | split L2 full | concat L2 full |",
                "|---|---|---|---|---|---|---|"])
    for population in ("out_real", "examples"):
        for kind in ("GEMM", "Conv"):
            group = [layer for layer in layers
                     if layer["population"] == population and layer["type"] == kind]
            cells = [population, kind, str(len(group))]
            for level in levels:
                for layout in LAYOUTS:
                    full = sum(results[label(layer), layout, level]["core_min"] == levels[level]["sets"]
                               for layer in group)
                    cells.append(f"{full}/{len(group)}" if group else "—")
            out.append("| " + " | ".join(cells) + " |")
    a07 = [layer for layer in layers if layer["benchmark"].startswith("A07/")]
    out.extend(["",
                f"A07 contributes {len(a07)} GEMM layers. "
                "All GEMM layers use the identical `[cout_blk | cin_blk]` flatten in "
                "both policies, so their global reach, per-core reach and imbalance "
                "are identical at both levels. A07's per-core line intervals contain "
                f"{min(layer['slice'] * layer['D'] for layer in a07)}–"
                f"{max(layer['slice'] * layer['D'] for layer in a07)} lines; "
                f"{sum(results[label(layer), LAYOUTS[0], 'L1']['core_min'] == levels['L1']['sets'] for layer in a07)}/{len(a07)} "
                "reach every L1 set per core and "
                f"{sum(results[label(layer), LAYOUTS[0], 'L2']['core_min'] == levels['L2']['sets'] for layer in a07)}/{len(a07)} "
                "reach every L2 set per core. Concat's potential differences occur "
                "in multi-position convolutions, not in this GEMM population.", "",
                "### Layers below full per-core L1 reach", "",
                "Every layer below 100% minimum per-core L1 reach is listed here:", ""])
    l1_sets = levels["L1"]["sets"]
    deficient = []
    for layer in layers:
        metrics = [results[label(layer), layout, "L1"] for layout in LAYOUTS]
        if all(metric["core_min"] == l1_sets for metric in metrics):
            continue
        deficient.append(layer)
        min_blocks = max(0, min(layer["slice"], layer["n_cout"] - (CORES - 1) * layer["slice"]))
        min_lines = min_blocks * layer["D"]
        reach = "; ".join(f"{layout}: min {pct(metric['core_min'], l1_sets)}, "
                          f"mean {pct(metric['core_mean'], l1_sets)}"
                          for layout, metric in zip(LAYOUTS, metrics))
        cause = (f"the smallest core slice has {min_blocks} COUT blocks × D={layer['D']} "
                 f"= {min_lines} lines, fewer than {l1_sets} sets; full reach is impossible "
                 "under any policy" if min_lines < l1_sets else
                 "the split layout maps distinct lines onto repeated sets")
        if min_blocks == 0:
            active = ceil_div(layer["n_cout"], layer["slice"])
            cause += (f"; this fixed contiguous-slice convention leaves {CORES - active} "
                      "cores empty, which sets the minimum to zero even if active cores reach all sets")
        if layer["kernel"] == 1:
            cause += "; for 1×1 both layouts reduce to `cout_blk*n_cin_blocks + cin_blk`"
        if layer["lines"] < levels["L1"]["lines"]:
            cause += (f"; the entire layer is also L1-capacity-bound "
                      f"({layer['lines']} < {levels['L1']['lines']} lines)")
        out.append(f"- `{label(layer)}` — {reach}. Cause: {cause}.")
    if not deficient:
        out.append("- None.")
    out.extend(["",
                f"The other {len(layers) - len(deficient)} layers reach every L1 set on "
                "every core under both policies. For concat, a core's contiguous COUT "
                "slice gives a contiguous interval of `owned_cout_blocks*D` lines: "
                "it reaches all sets exactly when that interval has at least `num_sets` "
                "lines. `D < num_sets` alone therefore does not imply a reachability loss.", "",
                "On 3×3 layers the split layout's eight low-position residues plus the "
                "ninth position bias some sets even when reach is 100%; concat removes "
                "the ragged gaps and spreads consecutive valid lines with counts differing "
                "by at most one. The L2 table also shows differences in per-core reach. "
                "On 1×1 layers the policies are identical, so concat cannot improve "
                "their reach or imbalance. A full-set reach or improved balance alone "
                "does not establish a runtime or hit-rate improvement.", ""])
    return "\n".join(out)


def main():
    output = Path(__file__).with_name("RESULTS.md")
    output.write_text(render(), encoding="utf-8")
    print("Wrote " + str(output))


if __name__ == "__main__":
    main()
