#!/usr/bin/env python3
"""S0 for the scheduler-only scaling experiment (T76, user-ordered 2026-11-16).

Scale-out-vs-scale-up at equal total weight capacity, solved by the Gurobi
scheduler alone (no trace simulation):

  point   total    single (1 node, 64 PE)   multi (N nodes x 4 PE)
  x1      128 KiB  spad 128 KiB             N=1: LB 64 KiB, GB 64 KiB
  x2      256 KiB  spad 256 KiB             N=2: LB 64 KiB each, GB 128 KiB
  x4      512 KiB  spad 512 KiB             N=4: LB 64 KiB each, GB 256 KiB

psum/vmem capacities stay at the eval_scaling S0 values (the sweep varies
weight capacity only). Both sides reuse the fig12 node mapspace from
../configs/mapspaces_{arch}_multi (COUT spatial 4 per core), so the only
knobs here are node instances and buffer entries, derived by editing the
existing x1 YAMLs.
"""

from __future__ import annotations

import copy
import json
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ES = HERE.parent
CFG = HERE / "configs"

ARCHES = ("spinalflow", "ptb", "loas", "prosperity", "gustavsnn")
MULTIPLIERS = (1, 2, 4)
BASE_WEIGHT = 131072  # 128 KiB total at x1, 1-byte entries
LB_WEIGHT = 65536     # fixed per-node LB on the multi side

HEADER = (
    "# Generated by sched_scaling/make_configs.py (T76 S0); do not hand-edit.\n"
    "# Scheduler-only scaling experiment, 2026-11-16.\n"
)


def storage_by_name(doc: dict, name: str) -> dict:
    for level in doc["arch"]["storage"]:
        if level["name"] == name:
            return level
    raise KeyError(name)


def main() -> None:
    CFG.mkdir(parents=True, exist_ok=True)
    points = []
    for arch in ARCHES:
        for side in ("single", "multi"):
            source = ES / "configs" / f"arch_{arch}_{side}_x1.yaml"
            base = yaml.safe_load(source.read_text())
            for m in MULTIPLIERS:
                doc = copy.deepcopy(base)
                node = storage_by_name(doc, "NodeLevel")
                if side == "single":
                    node["instances"] = 1
                    node["local_buffer"]["entries"]["weight"] = BASE_WEIGHT * m
                    total = BASE_WEIGHT * m
                else:
                    node["instances"] = m
                    node["local_buffer"]["entries"]["weight"] = LB_WEIGHT
                    noc = storage_by_name(doc, "NoCLevel")
                    noc["entries"]["weight"] = LB_WEIGHT * m
                    total = m * LB_WEIGHT + LB_WEIGHT * m
                if total != BASE_WEIGHT * m:
                    raise SystemExit(
                        f"{arch} {side} x{m}: total weight {total} != {BASE_WEIGHT * m}")
                out = CFG / f"arch_{arch}_{side}_x{m}.yaml"
                out.write_text(HEADER + yaml.safe_dump(doc, sort_keys=False))
                points.append({
                    "arch": arch, "side": side, "multiplier": m,
                    "arch_yaml": f"configs/arch_{arch}_{side}_x{m}.yaml",
                    # Both sides use the fig12 node mapspace (COUT spatial 4):
                    # the user's spec maps every core "按照之前multi-core的mapspace".
                    "mapspace_dir": f"../configs/mapspaces_{arch}_multi",
                    "total_weight_bytes": BASE_WEIGHT * m,
                })
    manifest = {
        "capture": "B09/loas_vgg16_T4_n500",
        "experiment": "scheduler_only_scaling",
        "architectures": list(ARCHES),
        "sides": ["single", "multi"],
        "multipliers": list(MULTIPLIERS),
        "multi_nodes_per_multiplier": {str(m): m for m in MULTIPLIERS},
        "points": points,
    }
    (CFG / "sweep_config.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"wrote {len(points)} arch yamls + sweep_config.json under {CFG}")


if __name__ == "__main__":
    main()
