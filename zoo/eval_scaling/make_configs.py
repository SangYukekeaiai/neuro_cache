#!/usr/bin/env python3
"""Generate the eval_scaling S0 configuration snapshot.

The generated mapspaces are copies of the five campaign mapspaces.  The only
dataflow change is the COUT spatial factor: one node's worth (64) on the
single-node side and one node's worth (4) on the multi-node side.
"""

from __future__ import annotations

import copy
import hashlib
import json
from pathlib import Path
from typing import Any

import yaml


HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
CFG = HERE / "configs"

ARCHES = ("spinalflow", "ptb", "loas", "prosperity", "gustavsnn")
SIDES = ("single", "multi")
MULTIPLIERS = (1, 2, 4)
CAPTURE = "B09/loas_vgg16_T4_n500"
CAPTURE_META = Path("/work/nvme/bebv/yyu9/input_trace_delta") / CAPTURE / "meta.json"
SOURCE_MAPSPACE_DIR = REPO / "zoo" / "wt500_fig3cfg" / "mapspaces"
CACHE_BASE = REPO / "examples" / "cache" / "base.json"

HEADER = (
    "# Generated by make_configs.py (S0); do not hand-edit.\n"
    "# eval_scaling configuration snapshot, 2026-11-16.\n"
)


def arch_yaml(arch: str, side: str, multiplier: int) -> dict[str, Any]:
    """Return one architecture config, including the requested capacity point."""

    if arch not in ARCHES:
        raise ValueError(f"unknown architecture: {arch}")
    if side not in SIDES:
        raise ValueError(f"unknown side: {side}")
    if multiplier not in MULTIPLIERS:
        raise ValueError(f"unknown multiplier: {multiplier}")

    if side == "single":
        node = {
            "name": "NodeLevel",
            "instances": 1,
            "pe": {"num_pes": 64},
            "local_buffer": {
                "entries": {
                    "weight": 1048576 * multiplier,
                    "psum": 16384,
                    "vmem": 16384,
                }
            },
        }
        noc = {"name": "NoCLevel", "instances": 1}
    else:
        node = {
            "name": "NodeLevel",
            "instances": 16,
            "pe": {"num_pes": 4},
            "local_buffer": {
                "entries": {
                    "weight": 32768 * multiplier,
                    "psum": 1024,
                    "vmem": 1024,
                }
            },
        }
        noc = {
            "name": "NoCLevel",
            "entries": {
                "weight": 524288 * multiplier,
                "psum": 65536,
                "vmem": 65536,
            },
            "instances": 1,
        }

    return {
        "arch": {
            "bitwidths": {
                "BW_WEIGHT": 8,
                "BW_PSUM": 16,
                "BW_VMEM": 32,
                "DRAM_LATENCY": 0.25,
            },
            "single_node": side == "single",
            "storage": [node, noc, {"name": "OffChip", "instances": 1}],
        },
    }


def _load_yaml(path: Path) -> dict[str, Any]:
    value = yaml.safe_load(path.read_text())
    if not isinstance(value, dict):
        raise ValueError(f"{path} must contain a YAML mapping")
    return value


def _changed_paths(before: Any, after: Any, prefix: tuple[Any, ...] = ()) -> set[tuple[Any, ...]]:
    """Return the leaf paths whose values differ between two YAML objects."""

    if isinstance(before, dict) and isinstance(after, dict):
        paths: set[tuple[Any, ...]] = set()
        for key in set(before) | set(after):
            if key not in before or key not in after:
                paths.add(prefix + (key,))
            else:
                paths.update(_changed_paths(before[key], after[key], prefix + (key,)))
        return paths
    if isinstance(before, list) and isinstance(after, list):
        if len(before) != len(after):
            return {prefix}
        paths: set[tuple[Any, ...]] = set()
        for index, (left, right) in enumerate(zip(before, after)):
            paths.update(_changed_paths(left, right, prefix + (index,)))
        return paths
    return set() if before == after else {prefix}


def _spatial_product(value: dict[str, Any]) -> int:
    capacities = value["dataflow"]["node_dim_capacity"]
    product = 1
    for capacity in capacities.values():
        if isinstance(capacity, dict) and "spatial" in capacity:
            product *= int(capacity["spatial"])
    return product


def _mapspace_for(source: Path, side: str) -> dict[str, Any]:
    """Copy a campaign mapspace and fill the requested node spatial product."""

    if side not in SIDES:
        raise ValueError(f"unknown side: {side}")
    original = _load_yaml(source)
    try:
        capacities = original["dataflow"]["node_dim_capacity"]
        cout = capacities["COUT"]
    except (KeyError, TypeError) as exc:
        raise ValueError(
            f"{source}: no unambiguous dataflow.node_dim_capacity.COUT field"
        ) from exc
    if not isinstance(capacities, dict):
        raise ValueError(f"{source}: node_dim_capacity is not a mapping")
    if not isinstance(cout, dict) or "spatial" not in cout:
        raise ValueError(
            f"{source}: COUT has no spatial dimension; refusing to guess a split"
        )

    target_product = 64 if side == "single" else 4
    other_product = 1
    for dim, capacity in capacities.items():
        if dim == "COUT":
            continue
        if isinstance(capacity, dict) and "spatial" in capacity:
            try:
                other_product *= int(capacity["spatial"])
            except (TypeError, ValueError) as exc:
                raise ValueError(
                    f"{source}: non-integer spatial factor for {dim!r}"
                ) from exc
    if target_product % other_product:
        raise ValueError(
            f"{source}: target spatial product {target_product} is not divisible "
            f"by non-COUT spatial product {other_product}"
        )
    cout_target = target_product // other_product
    value = copy.deepcopy(original)
    value["dataflow"]["node_dim_capacity"]["COUT"]["spatial"] = cout_target
    changed = _changed_paths(original, value)
    expected_change = {
        ("dataflow", "node_dim_capacity", "COUT", "spatial")
    }
    if changed - expected_change:
        raise AssertionError(
            f"{source}: mapspace changed paths {sorted(changed)!r}; "
            f"expected only COUT.spatial"
        )
    if _spatial_product(value) != target_product:
        raise AssertionError(
            f"{source}: generated spatial product {_spatial_product(value)} "
            f"does not equal {target_product}"
        )
    return value


def _write_yaml(path: Path, value: dict[str, Any], prefix: str = HEADER) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(prefix + yaml.safe_dump(value, sort_keys=False))


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _repo_relative(path: Path) -> str:
    return path.resolve().relative_to(REPO).as_posix()


def _arch_weight_capacity(path: Path) -> int:
    data = _load_yaml(path)["arch"]
    storage = {level["name"]: level for level in data["storage"]}
    node = storage["NodeLevel"]
    local_weight = node.get("local_buffer", {}).get("entries", {}).get("weight", 0)
    node_total = int(node.get("instances", 1)) * int(local_weight)
    noc = storage.get("NoCLevel", {})
    noc_weight = noc.get("entries", {}).get("weight", 0)
    noc_total = int(noc.get("instances", 1)) * int(noc_weight)
    return node_total + noc_total


def _assert_equal_capacity(arch: str, multiplier: int) -> None:
    single_path = CFG / f"arch_{arch}_single_x{multiplier}.yaml"
    multi_path = CFG / f"arch_{arch}_multi_x{multiplier}.yaml"
    if not single_path.is_file() or not multi_path.is_file():
        raise AssertionError(
            f"cannot check equal capacity before both artifacts exist: "
            f"{single_path}, {multi_path}"
        )
    single = _arch_weight_capacity(single_path)
    multi = _arch_weight_capacity(multi_path)
    assert multi == single, (
        f"unequal weight capacity for {arch} at x{multiplier}: "
        f"single={single}, multi={multi}"
    )


def _write_cache_configs() -> list[Path]:
    base = json.loads(CACHE_BASE.read_text())
    outputs = []
    for multiplier in MULTIPLIERS:
        config = copy.deepcopy(base)
        config["l1_size_bytes"] = 32768 * multiplier
        config["l2_size_bytes"] = 524288 * multiplier
        path = CFG / f"cache_x{multiplier}.json"
        path.write_text(json.dumps(config, indent=2) + "\n")
        outputs.append(path)
    for multiplier, path in zip(MULTIPLIERS, outputs):
        config = json.loads(path.read_text())
        total = 16 * int(config["l1_size_bytes"]) + int(config["l2_size_bytes"])
        expected = 1048576 * multiplier
        assert total == expected, (
            f"unequal cache weight capacity at x{multiplier}: "
            f"total={total}, expected={expected}"
        )
    return outputs


def _write_provenance() -> Path:
    if not CAPTURE_META.is_file():
        raise FileNotFoundError(f"missing capture metadata: {CAPTURE_META}")
    if not CACHE_BASE.is_file():
        raise FileNotFoundError(f"missing cache template: {CACHE_BASE}")
    sources = {}
    for arch in ARCHES:
        source = SOURCE_MAPSPACE_DIR / f"{arch}.yaml"
        if not source.is_file():
            raise FileNotFoundError(f"missing source mapspace: {source}")
        sources[arch] = {
            "path": _repo_relative(source),
            "sha256": _sha256(source),
        }

    provenance = {
        "capture": {
            "name": CAPTURE,
            "meta_json": str(CAPTURE_META),
            "sha256": _sha256(CAPTURE_META),
        },
        "source_mapspaces": sources,
        "generated": {
            "script": "zoo/eval_scaling/make_configs.py",
            "architectures": list(ARCHES),
            "sides": list(SIDES),
            "multipliers": list(MULTIPLIERS),
            "mapspace_rule": (
                "copy each campaign dataflow and change only COUT.spatial "
                "so the full spatial product is 64 (single) or 4 (multi)"
            ),
            "cache_template": _repo_relative(CACHE_BASE),
            "cache_template_sha256": _sha256(CACHE_BASE),
        },
    }
    path = CFG / "provenance.json"
    path.write_text(json.dumps(provenance, indent=2) + "\n")
    return path


def _readback(paths: list[Path]) -> None:
    """Check that every generated YAML/JSON file parses and is non-scalar."""

    for path in paths:
        if path.suffix in {".yaml", ".yml"}:
            value = yaml.safe_load(path.read_text())
        elif path.suffix == ".json":
            value = json.loads(path.read_text())
        else:
            raise AssertionError(f"unexpected generated suffix: {path}")
        if not isinstance(value, (dict, list)):
            raise AssertionError(f"empty or scalar generated file: {path}")


def main() -> None:
    CFG.mkdir(parents=True, exist_ok=True)
    generated: list[Path] = []
    points = []

    for arch in ARCHES:
        source = SOURCE_MAPSPACE_DIR / f"{arch}.yaml"
        for side in SIDES:
            mapspace_dir = CFG / f"mapspaces_{arch}_{side}"
            mapspace_path = mapspace_dir / f"{arch}.yaml"
            mapspace = _mapspace_for(source, side)
            target_product = 64 if side == "single" else 4
            mapspace_prefix = (
                HEADER
                + f"# source: {_repo_relative(source)}; "
                f"COUT.spatial adjusted so the full spatial product is "
                f"{target_product} for the {side} machine.\n"
            )
            _write_yaml(mapspace_path, mapspace, prefix=mapspace_prefix)
            written_mapspace = _load_yaml(mapspace_path)
            if written_mapspace != mapspace:
                raise AssertionError(
                    f"{mapspace_path}: serialized dataflow differs from generated data"
                )
            if _spatial_product(written_mapspace) != target_product:
                raise AssertionError(
                    f"{mapspace_path}: spatial product is "
                    f"{_spatial_product(written_mapspace)}, expected {target_product}"
                )
            generated.append(mapspace_path)

            for multiplier in MULTIPLIERS:
                arch_path = CFG / f"arch_{arch}_{side}_x{multiplier}.yaml"
                _write_yaml(arch_path, arch_yaml(arch, side, multiplier))
                generated.append(arch_path)
                points.append(
                    {
                        "arch": arch,
                        "side": side,
                        "multiplier": multiplier,
                        "arch_yaml": arch_path.relative_to(HERE).as_posix(),
                        "mapspace_dir": mapspace_dir.relative_to(HERE).as_posix(),
                        "total_weight_bytes": 1048576 * multiplier,
                    }
                )
        for multiplier in MULTIPLIERS:
            _assert_equal_capacity(arch, multiplier)

    cache_paths = _write_cache_configs()
    generated.extend(cache_paths)

    manifest = {
        "capture": CAPTURE,
        "samples": list(range(10)),
        "architectures": list(ARCHES),
        "sides": list(SIDES),
        "multipliers": list(MULTIPLIERS),
        "points": points,
    }
    manifest_path = CFG / "sweep_config.json"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    generated.append(manifest_path)

    provenance_path = _write_provenance()
    generated.append(provenance_path)
    _readback(generated)

    arch_paths = list(CFG.glob("arch_*.yaml"))
    mapspace_paths = list(CFG.glob("mapspaces_*/*.yaml"))
    mapspace_dirs = [path for path in CFG.glob("mapspaces_*") if path.is_dir()]
    assert len(arch_paths) == 30, f"expected 30 arch yamls, found {len(arch_paths)}"
    assert len(mapspace_paths) == 10, (
        f"expected 10 mapspace yamls, found {len(mapspace_paths)}"
    )
    assert len(mapspace_dirs) == 10, (
        f"expected 10 mapspace directories, found {len(mapspace_dirs)}"
    )
    assert len(points) == 30
    print(
        f"wrote {len(arch_paths)} arch yamls + {len(mapspace_paths)} mapspace yamls "
        f"+ {len(cache_paths)} cache configs + sweep_config.json + provenance.json"
    )


if __name__ == "__main__":
    main()
