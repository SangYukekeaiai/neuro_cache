#!/usr/bin/env python3
"""S0 for eval_scaling: emit the sweep's arch yamls, mapspaces and manifest.

Boss spec 2026-11-16 (execution_plan.md): single node COUT=64, lb 1024KB
x{1,2,4,8,16}; multi-node 16 nodes COUT=4, lb 32KB x m, GB 512KB x m.
Entries are elements; weights are 8-bit, so weight entries == bytes.
State buffers (psum/vmem) are held constant across the sweep (C9): per-node
1024 each on the multi side, 16x that (16384) on the single node so total
state capacity matches and the 64 COUT lanes fit.
"""

import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
CFG = HERE / "configs"
MULTIPLIERS = (1, 2, 4, 8, 16)

HEADER = (
    "# Generated by make_configs.py (S0); do not hand-edit.\n"
    "# eval_scaling sweep, boss spec 2026-11-16.\n"
)


def arch_yaml(side: str, m: int) -> str:
    if side == "single":
        body = f"""arch:
  bitwidths:
    BW_WEIGHT: 8
    BW_PSUM: 16
    BW_VMEM: 32
    DRAM_LATENCY: 0.25
  single_node: true
  storage:
  - name: NodeLevel
    instances: 1
    pe:
      num_pes: 64
    local_buffer:
      entries:
        weight: {1048576 * m}
        psum: 16384
        vmem: 16384
  - name: NoCLevel
    instances: 1
  - name: OffChip
    instances: 1
"""
    else:
        body = f"""arch:
  bitwidths:
    BW_WEIGHT: 8
    BW_PSUM: 16
    BW_VMEM: 32
    DRAM_LATENCY: 0.25
  single_node: false
  storage:
  - name: NodeLevel
    instances: 16
    pe:
      num_pes: 4
    local_buffer:
      entries:
        weight: {32768 * m}
        psum: 1024
        vmem: 1024
  - name: NoCLevel
    entries:
      weight: {524288 * m}
      psum: 65536
      vmem: 65536
    instances: 1
  - name: OffChip
    instances: 1
"""
    return HEADER + body


MAPSPACE = {
    "single": """dataflow:
  node_dim_capacity:
    KH:   full
    KW:   full
    CIN:  full
    T:    full
    COUT: {spatial: 64}
""",
    "multi": """dataflow:
  node_dim_capacity:
    KH:   full
    KW:   full
    CIN:  full
    T:    full
    COUT: {spatial: 4}
""",
}


def main() -> None:
    points = []
    for side in ("single", "multi"):
        ms_dir = CFG / f"mapspaces_{side}"
        ms_dir.mkdir(parents=True, exist_ok=True)
        (ms_dir / "loas.yaml").write_text(HEADER + MAPSPACE[side])
        for m in MULTIPLIERS:
            p = CFG / f"arch_{side}_x{m}.yaml"
            p.write_text(arch_yaml(side, m))
            points.append({
                "side": side,
                "multiplier": m,
                "arch_yaml": p.relative_to(HERE).as_posix(),
                "mapspace_dir": ms_dir.relative_to(HERE).as_posix(),
                "total_weight_bytes": 1048576 * m,
            })
    manifest = {
        "capture": "B09/loas_vgg16_T4_n500",
        "samples": list(range(10)),
        "arch": "loas",
        "points": points,
    }
    (CFG / "sweep_config.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"wrote {len(points)} arch yamls + 2 mapspaces + sweep_config.json")
    # self-check: equal total weight storage at every multiplier
    for m in MULTIPLIERS:
        assert 16 * 32768 * m + 524288 * m == 1048576 * m


if __name__ == "__main__":
    main()
